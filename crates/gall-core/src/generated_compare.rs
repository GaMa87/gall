//! Which files are generated, so that a comparison can collapse them by default. The answer is presentation
//! only: nothing here changes what is staged, exported as a patch, merged or synchronized, and the counts of the
//! changes stay as they are. Every classification carries a reason code, so the interface can say why.
//!
//! The rules are narrow on purpose (a false positive hides a real change behind a click):
//! * a **lockfile** is a file with a well-known lockfile name;
//! * an **artifact path** has a folder that only holds build output (`node_modules`, `dist`, `__pycache__`, …);
//! * a **generated header** is a marker such as `@generated` or `Code generated … DO NOT EDIT` inside a *comment*
//!   in the first lines (the same words in a string literal or in code do not count);
//! * a **minified bundle** is a script or style file with the name `.min.` or with very long lines.

use serde::Serialize;

/// Lines of the beginning of a file that are searched for a generated header.
const HEADER_LINES: usize = 12;
/// A line this long (in characters) in a script or style file is minified code.
const MINIFIED_LINE: usize = 1_000;
/// The text of a bundle must also be at least this long (bytes) to count as minified without `.min.`.
const MINIFIED_MIN_BYTES: usize = 2_048;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub enum Reason {
    Lockfile,
    ArtifactPath,
    GeneratedHeader,
    MinifiedBundle,
    /// The repository says so: `linguist-generated` in a `.gitattributes` file.
    GitAttributes,
    /// Matched a user-configured extra generated file pattern in Settings.
    CustomPattern,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Generated {
    pub reason: Reason,
}

const LOCKFILES: &[&str] = &[
    "cargo.lock",
    "package-lock.json",
    "npm-shrinkwrap.json",
    "yarn.lock",
    "pnpm-lock.yaml",
    "bun.lock",
    "gemfile.lock",
    "poetry.lock",
    "pipfile.lock",
    "composer.lock",
    "go.sum",
    "flake.lock",
    "packages.lock.json",
    "mix.lock",
    "pubspec.lock",
];

const ARTIFACT_FOLDERS: &[&str] = &[
    "node_modules",
    "dist",
    "__pycache__",
    ".next",
    ".nuxt",
    ".gradle",
];

/// The file name and the folders of a path (either separator).
fn parts(path: &str) -> (&str, Vec<&str>) {
    let mut it: Vec<&str> = path.split(['/', '\\']).filter(|p| !p.is_empty()).collect();
    let name = it.pop().unwrap_or("");
    (name, it)
}

/// Whether a line is a comment in the syntax a source file of this name can have. Documentation comments
/// (`///`, `//!`) and prose files are no header: they talk *about* generated code.
fn is_comment_line(name: &str, line: &str) -> bool {
    let t = line.trim_start();
    let prose = [".md", ".markdown", ".txt", ".rst", ".adoc"]
        .iter()
        .any(|e| name.to_ascii_lowercase().ends_with(e));
    if prose || t.starts_with("///") || t.starts_with("//!") {
        return false;
    }
    t.starts_with("//")
        || t.starts_with('#')
        || t.starts_with("/*")
        || t.starts_with('*')
        || t.starts_with("--")
        || t.starts_with(';')
        || t.starts_with("<!--")
}

fn has_header_marker(comment: &str) -> bool {
    let l = comment.to_ascii_lowercase();
    l.contains("@generated")
        || (l.contains("code generated") && l.contains("do not edit"))
        || l.contains("this file is automatically generated")
        || l.contains("this file was automatically generated")
        || l.contains("auto-generated file")
        || l.contains("autogenerated file")
        || l.contains("do not edit this file")
}

fn is_script_or_style(name: &str) -> bool {
    let l = name.to_ascii_lowercase();
    [".js", ".mjs", ".cjs", ".css", ".jsx"]
        .iter()
        .any(|e| l.ends_with(e))
}

/// Classifies a file by its path and its text (only the beginning and the line lengths are read).
pub fn classify(path: &str, text: &str) -> Option<Generated> {
    let (name, folders) = parts(path);
    let lower = name.to_ascii_lowercase();
    if LOCKFILES.contains(&lower.as_str()) {
        return Some(Generated {
            reason: Reason::Lockfile,
        });
    }
    if folders
        .iter()
        .any(|f| ARTIFACT_FOLDERS.contains(&f.to_ascii_lowercase().as_str()))
    {
        return Some(Generated {
            reason: Reason::ArtifactPath,
        });
    }
    if text
        .lines()
        .take(HEADER_LINES)
        .any(|l| is_comment_line(name, l) && has_header_marker(l))
    {
        return Some(Generated {
            reason: Reason::GeneratedHeader,
        });
    }
    if is_script_or_style(name) {
        let named = lower.contains(".min.");
        let long = text.len() >= MINIFIED_MIN_BYTES
            && text.lines().any(|l| l.chars().count() >= MINIFIED_LINE);
        if named || long {
            return Some(Generated {
                reason: Reason::MinifiedBundle,
            });
        }
    }
    None
}

/// What the `.gitattributes` files from the folder of `file` up to the repository root say about `linguist-generated`:
/// `Some(true)` when it is set (`linguist-generated` or `linguist-generated=true`), `Some(false)` when it is unset
/// (`-linguist-generated` or `=false`), `None` when nothing names the file. A closer file wins over a farther one and a
/// later line over an earlier one, as in Git. Patterns follow the rules of `.gitignore` for names (a pattern without a
/// slash matches a name at any depth; one with a slash is relative to the folder of its file); folder-only patterns
/// (`dir/`) are not looked at.
pub fn linguist_generated(file: &std::path::Path) -> Option<bool> {
    let mut folder = file.parent()?;
    let mut chain: Vec<&std::path::Path> = Vec::new();
    loop {
        chain.push(folder);
        if folder.join(".git").exists() {
            break;
        }
        folder = folder.parent()?;
    }
    // The closest file first.
    for dir in chain {
        let Ok(text) = std::fs::read_to_string(dir.join(".gitattributes")) else {
            continue;
        };
        let Ok(relative) = file.strip_prefix(dir) else {
            continue;
        };
        let relative = relative.to_string_lossy().replace('\\', "/");
        let mut answer = None;
        for line in text.lines() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let mut fields = line.split_whitespace();
            let Some(pattern) = fields.next() else {
                continue;
            };
            if pattern.ends_with('/') || pattern.starts_with('[') {
                continue;
            }
            let set = fields.fold(None, |found, attr| match attr {
                "linguist-generated" | "linguist-generated=true" => Some(true),
                "-linguist-generated" | "linguist-generated=false" => Some(false),
                _ => found,
            });
            let Some(set) = set else { continue };
            let anchored = pattern.trim_start_matches('/');
            let glob = if pattern.contains('/') {
                anchored.to_owned()
            } else {
                format!("**/{anchored}")
            };
            let matched = globset::GlobBuilder::new(&glob)
                .literal_separator(true)
                .build()
                .is_ok_and(|g| g.compile_matcher().is_match(&relative));
            if matched {
                answer = Some(set);
            }
        }
        if answer.is_some() {
            return answer;
        }
    }
    None
}

/// Whether `path` matches any user-configured extra generated pattern (gitignore-like globs: patterns without `/`
/// match the file name at any depth; patterns with `/` match relative to any suffix of the normalized path).
/// Invalid patterns are ignored.
fn matches_extra_pattern(path: &str, patterns: &[String]) -> bool {
    if patterns.is_empty() {
        return false;
    }
    let normalized = path.replace('\\', "/");
    let trimmed_path = normalized.trim_start_matches('/');
    for raw in patterns {
        let pattern = raw.trim();
        if pattern.is_empty() || pattern.starts_with('#') || pattern.ends_with('/') {
            continue;
        }
        let anchored = pattern.trim_start_matches('/');
        let glob = if anchored.starts_with("**/") {
            anchored.to_owned()
        } else {
            format!("**/{anchored}")
        };
        let matched = globset::GlobBuilder::new(&glob)
            .literal_separator(true)
            .build()
            .is_ok_and(|g| {
                let m = g.compile_matcher();
                m.is_match(trimmed_path) || m.is_match(&normalized)
            });
        if matched {
            return true;
        }
    }
    false
}

/// `classify`, plus user-configured extra glob patterns.
pub fn classify_with_patterns(
    path: &str,
    text: &str,
    extra_patterns: &[String],
) -> Option<Generated> {
    classify(path, text).or_else(|| {
        matches_extra_pattern(path, extra_patterns).then_some(Generated {
            reason: Reason::CustomPattern,
        })
    })
}

/// `classify`, and when the path and text name no reason, the `.gitattributes` of the repository the file is in
/// (`linguist-generated`). Reads the files that name the attribute only; nothing is run.
pub fn classify_in_repo(path: &str, text: &str) -> Option<Generated> {
    classify_in_repo_with_patterns(path, text, &[])
}

/// `classify_in_repo` with additional user-configured generated file patterns. An explicit `-linguist-generated`
/// in `.gitattributes` overrides both built-in rules and extra patterns.
pub fn classify_in_repo_with_patterns(
    path: &str,
    text: &str,
    extra_patterns: &[String],
) -> Option<Generated> {
    let by_content = classify(path, text);
    match linguist_generated(std::path::Path::new(path)) {
        Some(false) => None,
        Some(true) => by_content.or(Some(Generated {
            reason: Reason::GitAttributes,
        })),
        None => by_content.or_else(|| {
            matches_extra_pattern(path, extra_patterns).then_some(Generated {
                reason: Reason::CustomPattern,
            })
        }),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn reason(path: &str, text: &str) -> Option<Reason> {
        classify(path, text).map(|g| g.reason)
    }

    #[test]
    fn lockfiles_by_name_in_any_folder() {
        assert_eq!(reason("Cargo.lock", ""), Some(Reason::Lockfile));
        assert_eq!(reason("ui/package-lock.json", "{}"), Some(Reason::Lockfile));
        assert_eq!(
            reason("C:\\work\\app\\yarn.lock", ""),
            Some(Reason::Lockfile)
        );
        assert_eq!(reason("notes/lock.txt", ""), None);
        assert_eq!(reason("src/cargo_lock.rs", ""), None);
    }

    #[test]
    fn artifact_folders_but_not_similar_names() {
        assert_eq!(
            reason("web/node_modules/x/index.js", ""),
            Some(Reason::ArtifactPath)
        );
        assert_eq!(reason("dist/app.js", ""), Some(Reason::ArtifactPath));
        assert_eq!(reason("src/distance.rs", ""), None);
        assert_eq!(reason("src/dist_tools/lib.rs", ""), None);
        // `build` and `target` hold source in many projects: not an artifact by name alone.
        assert_eq!(reason("build/make.rs", ""), None);
        assert_eq!(reason("src/coverage/mod.rs", ""), None);
    }

    #[test]
    fn generated_header_only_in_a_comment_in_the_first_lines() {
        assert_eq!(
            reason("a.rs", "// @generated by tool\nfn x() {}\n"),
            Some(Reason::GeneratedHeader)
        );
        assert_eq!(
            reason(
                "a.go",
                "// Code generated by protoc. DO NOT EDIT.\npackage a\n"
            ),
            Some(Reason::GeneratedHeader)
        );
        assert_eq!(
            reason("a.py", "# This file is automatically generated\nx = 1\n"),
            Some(Reason::GeneratedHeader)
        );
        assert_eq!(
            reason("a.c", "/* @generated */\nint x;\n"),
            Some(Reason::GeneratedHeader)
        );
        // Documentation comments and prose files talk about generated code; they are not generated.
        assert_eq!(
            reason("a.rs", "//! Marks `@generated` files.\nfn x() {}\n"),
            None
        );
        assert_eq!(reason("notes.md", "# Autogenerated file notes\n"), None);
        // The same words in a string literal or in code are no header.
        assert_eq!(reason("a.rs", "let s = \"// @generated\";\n"), None);
        assert_eq!(
            reason(
                "a.rs",
                "const NOTE: &str = \"Code generated, DO NOT EDIT\";\n"
            ),
            None
        );
        // Far down the file is no header either.
        let late = format!("{}// @generated\n", "x\n".repeat(HEADER_LINES + 1));
        assert_eq!(reason("a.rs", &late), None);
    }

    #[test]
    fn minified_bundles_by_name_or_by_long_lines_in_scripts_and_styles() {
        assert_eq!(reason("app.min.js", "a"), Some(Reason::MinifiedBundle));
        let long = format!("var a=1;{}\n", "x".repeat(MINIFIED_MIN_BYTES));
        assert_eq!(reason("bundle.js", &long), Some(Reason::MinifiedBundle));
        // A short file with one long line is not enough, nor is a long line in another kind of file.
        assert_eq!(reason("small.js", &"x".repeat(MINIFIED_LINE)), None);
        assert_eq!(reason("data.json", &long), None);
        assert_eq!(reason("notes.md", &long), None);
        assert_eq!(
            reason("normal.js", "function a() {\n  return 1;\n}\n"),
            None
        );
    }

    #[test]
    fn first_matching_rule_names_the_reason() {
        assert_eq!(reason("dist/Cargo.lock", ""), Some(Reason::Lockfile));
        assert_eq!(
            reason("dist/a.js", "// @generated\n"),
            Some(Reason::ArtifactPath)
        );
    }

    #[test]
    fn gitattributes_mark_generated_files_and_a_closer_file_or_a_negation_wins() {
        let d = tempfile::tempdir().unwrap();
        let root = d.path();
        std::fs::create_dir(root.join(".git")).unwrap();
        std::fs::create_dir_all(root.join("src/gen")).unwrap();
        std::fs::write(
            root.join(".gitattributes"),
            "# comment\n*.pb.go linguist-generated\n/api/schema.json linguist-generated=true\nsrc/gen/** linguist-generated\nkeep.pb.go -linguist-generated\n",
        )
        .unwrap();
        std::fs::write(
            root.join("src/gen/.gitattributes"),
            "inner.txt -linguist-generated\n",
        )
        .unwrap();
        let at = |rel: &str| root.join(rel);
        // A name at any depth, a rooted path, a folder glob.
        assert_eq!(linguist_generated(&at("x/y/model.pb.go")), Some(true));
        assert_eq!(linguist_generated(&at("api/schema.json")), Some(true));
        assert_eq!(linguist_generated(&at("other/schema.json")), None);
        assert_eq!(linguist_generated(&at("src/gen/out.rs")), Some(true));
        // Unset beats set, and the closer file wins.
        assert_eq!(linguist_generated(&at("keep.pb.go")), Some(false));
        assert_eq!(linguist_generated(&at("src/gen/inner.txt")), Some(false));
        // Not named: nothing.
        assert_eq!(linguist_generated(&at("src/main.rs")), None);
        // The classifier: the repository says generated for a file the content rules know nothing about, and `-` turns a
        // content rule off.
        let path = at("x/model.pb.go").to_string_lossy().into_owned();
        assert_eq!(
            classify_in_repo(&path, "package x\n").unwrap().reason,
            Reason::GitAttributes
        );
        let kept = at("keep.pb.go").to_string_lossy().into_owned();
        assert!(classify_in_repo(&kept, "// Code generated by x. DO NOT EDIT.\n").is_none());
        // Outside any repository nothing is read.
        assert_eq!(
            linguist_generated(std::path::Path::new("/nonexistent/a.pb.go")),
            None
        );
    }

    #[test]
    fn extra_generated_patterns_match_names_and_paths_and_respect_gitattributes_negation() {
        let extra = vec![
            "*.gen.ts".to_string(),
            "generated/*.rs".to_string(),
            "[invalid".to_string(),
        ];
        assert_eq!(
            classify_with_patterns("src/api.gen.ts", "", &extra).map(|g| g.reason),
            Some(Reason::CustomPattern)
        );
        assert_eq!(
            classify_with_patterns("/repo/generated/schema.rs", "", &extra).map(|g| g.reason),
            Some(Reason::CustomPattern)
        );
        assert_eq!(classify_with_patterns("src/main.ts", "", &extra), None);
        // Built-in lockfile rule still takes precedence over custom patterns.
        assert_eq!(
            classify_with_patterns("Cargo.lock", "", &[String::from("*.lock")]).map(|g| g.reason),
            Some(Reason::Lockfile)
        );
        // Explicit `-linguist-generated` in `.gitattributes` overrides an extra pattern.
        let d = tempfile::tempdir().unwrap();
        std::fs::create_dir(d.path().join(".git")).unwrap();
        std::fs::write(
            d.path().join(".gitattributes"),
            "keep.gen.ts -linguist-generated\n",
        )
        .unwrap();
        let kept = d.path().join("keep.gen.ts").to_string_lossy().into_owned();
        assert_eq!(classify_in_repo_with_patterns(&kept, "", &extra), None);
        let matched = d.path().join("other.gen.ts").to_string_lossy().into_owned();
        assert_eq!(
            classify_in_repo_with_patterns(&matched, "", &extra).map(|g| g.reason),
            Some(Reason::CustomPattern)
        );
    }
}
