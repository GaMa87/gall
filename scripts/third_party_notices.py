#!/usr/bin/env python3
"""Generates THIRD-PARTY-NOTICES.md from `cargo metadata` and ui/node_modules.

Lists every third-party Rust crate and npm production dependency with its
licence and source URL. Run from the repository root:  python3 scripts/third_party_notices.py
"""
import json
import pathlib
import subprocess

ROOT = pathlib.Path(__file__).resolve().parent.parent


def rust():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked"], cwd=ROOT))
    ours = {"gall", "gall-core"}
    return sorted(
        ((p["name"], p["version"], p.get("license") or "see repository", p.get("repository") or "")
         for p in meta["packages"] if p["name"] not in ours),
        key=lambda t: t[0].lower(),
    )


def npm():
    lock = json.loads((ROOT / "ui" / "package-lock.json").read_text(encoding="utf-8"))
    out = []
    for path, info in lock.get("packages", {}).items():
        if not path or info.get("dev"):
            continue
        pkg = ROOT / "ui" / path / "package.json"
        if not pkg.exists():
            continue
        d = json.loads(pkg.read_text())
        repo = d.get("repository")
        repo = repo.get("url", "") if isinstance(repo, dict) else (repo or "")
        out.append((d["name"], d.get("version", ""), d.get("license") or "see repository", repo))
    return sorted(set(out), key=lambda t: t[0].lower())


def table(rows):
    lines = ["| Package | Version | Licence | Source |", "|---|---|---|---|"]
    lines += [f"| {n} | {v} | {l} | {r} |" for n, v, l, r in rows]
    return "\n".join(lines)


def main():
    r, n = rust(), npm()
    text = f"""# Third-party notices

Gall is MIT licensed. It is built on the open-source components below,
each under its own licence. Licence texts are in the components' source
distributions (crates.io / npm). Generated by `scripts/third_party_notices.py`.

All licences are permissive (MIT, Apache-2.0, BSD, ISC, Zlib, Unicode, CC0…)
or weak file-level copyleft (MPL-2.0, used unmodified), which is compatible
with distributing Gall under MIT. Policy enforced in CI by `deny.toml`.

The compare view's syntax colouring uses the Sublime Text grammars bundled
by `two-face` (collected by the bat project), each under its own permissive
licence; see https://github.com/sharkdp/bat/tree/master/assets/syntaxes.

## Rust crates ({len(r)})

{table(r)}

## npm packages shipped in the UI ({len(n)})

{table(n)}

## Vendored assets

| Asset | Version | Licence | Source |
|---|---|---|---|
| Catppuccin Icons (file/folder icons, `ui/public/icons/catppuccin`) | 1.24.0 | MIT | https://github.com/catppuccin/zed-icons |
"""
    # UTF-8 and LF on every OS (Windows would write its ANSI code page and CRLF).
    (ROOT / "THIRD-PARTY-NOTICES.md").write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote THIRD-PARTY-NOTICES.md: {len(r)} crates, {len(n)} npm packages")


if __name__ == "__main__":
    main()
