def _t2_f3_05_batch_50_and_stale_cut_invalidation(ctx: RunContext) -> E2EResult:
    """Batch 50-file clipboard payload and stale cut invalidation after external delete."""
    if pending := require_selftest_mode(ctx, "e2e-clip-paste"):
        return pending
    with SandboxEnv("T2-F3-05", ctx.env_probe, allow_gui=True, multi_instance=True, dbus_required=True) as sb:
        src = sb.work / "src"
        dst = sb.work / "dst"
        dst2 = sb.work / "dst2"
        src.mkdir()
        dst.mkdir()
        dst2.mkdir()
        uris = []
        for i in range(50):
            p = src / f"item_{i:02d}.txt"
            p.write_text(f"{i}\n", encoding="utf-8")
            uris.append(f"file://{p}")
        owner1, err1 = start_clipboard_owner(
            sb,
            {"text/uri-list": ("\r\n".join(uris) + "\r\n").encode("utf-8")},
        )
        if err1 is not None:
            return err1
        try:
            proc, report, _ = run_gall_selftest(ctx, sb, "e2e-clip-paste", extra_args=[str(dst)])
        finally:
            stop_proc(owner1)
        if fail := check_selftest_outcome(proc, report, "e2e-clip-paste", sb=sb):
            return fail
        if "paste" not in report.lower():
            return E2EResult(Status.FAIL, "e2e-clip-paste report missing paste marker on 50-file batch", {"report": report})

        for i in range(50):
            copied = dst / f"item_{i:02d}.txt"
            if not copied.is_file() or copied.read_text(encoding="utf-8") != f"{i}\n":
                return E2EResult(Status.FAIL, f"50-file batch paste missed or corrupted {copied.name}")

        # Stale cut invalidation: put cut URI on clipboard then delete source before paste
        stale_src = src / "vanished_cut.txt"
        stale_src.write_text("cut-me\n", encoding="utf-8")
        owner2, err2 = start_clipboard_owner(
            sb,
            {"x-special/gnome-copied-files": f"cut\nfile://{stale_src}\n".encode("utf-8")},
        )
        if err2 is not None:
            return err2
        try:
            stale_src.unlink()
            proc2, report2, _ = run_gall_selftest(ctx, sb, "e2e-clip-paste", extra_args=[str(dst2)])
        finally:
            stop_proc(owner2)
        if fail := check_selftest_outcome(proc2, report2, "e2e-clip-paste", sb=sb):
            return fail
        if "paste" not in report2.lower():
            return E2EResult(Status.FAIL, "e2e-clip-paste report missing paste marker on stale cut", {"report": report2})
        if (dst2 / "vanished_cut.txt").exists():
            return E2EResult(Status.FAIL, "Stale deleted cut target unexpectedly materialized in dst2")
        return E2EResult(Status.PASS, "50-file batch clipboard & stale-cut invalidation verified")


